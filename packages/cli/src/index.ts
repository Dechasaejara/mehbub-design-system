#!/usr/bin/env node
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const args = process.argv.slice(2);
const command = args[0];
const options = Object.fromEntries(args.slice(1).filter(x => x.startsWith("--")).map(x => {
  const [key, ...value] = x.slice(2).split("=");
  return [key, value.join("=") || "true"];
}));

async function createClient() {
  const name = String(options.name ?? "client-new").toLowerCase().replace(/[^a-z0-9-]/g, "-");
  const preset = String(options.preset ?? "corporate");
  const framework = String(options.framework ?? "next");
  const target = resolve(process.cwd(), name);
  await mkdir(resolve(target, "brand"), { recursive: true });
  await writeFile(resolve(target, "brand/brand.tokens.json"), JSON.stringify({
    name,
    preset,
    colors: {
      primary: "#245B8F", onPrimary: "#FFFFFF", background: "#FFFFFF",
      surface: "#F5F7FA", text: "#142235", muted: "#64748B", border: "#DCE3EA"
    },
    typography: { fontFamily: "Inter, system-ui, sans-serif" },
    radius: { sm: "4px", md: "8px", lg: "12px", pill: "9999px" }
  }, null, 2));
  await writeFile(resolve(target, "README.md"), `# ${name}\n\nClient starter generated by Agency CLI.\n\nPreset: ${preset}\nFramework: ${framework}\n\nInstall your approved @agency packages and wire the generated brand tokens into the theme package before production.\n`);
  await writeFile(resolve(target, ".gitignore"), "node_modules\ndist\n.next\n.env*\n");
  console.log(`Created ${target}`);
  console.log("Next: add the appropriate framework app, install approved @agency packages, review brand tokens, and initialize Git.");
}

if (command === "create-client") await createClient();
else {
  console.log("Agency Design Platform CLI");
  console.log("Usage: agency create-client --name=client-name --preset=corporate --framework=next");
}
